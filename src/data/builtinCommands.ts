/** 将内置命令转换为 FavoriteCommand 格式（使用翻译后的文本） */
export function toFavorite(
  cmd: { command: string; desc: string; descKey?: string },
  category: string,
  categoryKey: string | undefined,
  icon: string,
  t: (key: string) => string,
): FavoriteCommand {
  const translatedCategory = categoryKey ? t(categoryKey) : `${icon} ${category}`
  return {
    id: nanoid(),
    command: cmd.command,
    note: cmd.descKey ? t(cmd.descKey) : cmd.desc,
    category: translatedCategory,
    createdAt: new Date().toISOString(),
    isBuiltin: true,
  }
}
