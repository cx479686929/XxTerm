/** 将内置命令转换为 FavoriteCommand 格式 */
export function toFavorite(cmd: { command: string; desc: string }, category: string, icon: string): FavoriteCommand {
  return {
    id: nanoid(),
    command: cmd.command,
    note: cmd.desc,
    category: `${icon} ${category}`,
    createdAt: new Date().toISOString(),
    isBuiltin: true,
  }
}
